def get_reason(signal: str, language: str = "en") -> str:
    """
    Returns the user-facing explanation for a given signal in the requested language.
    Language defaults to 'en' if missing or unsupported.
    """
    if not language:
        language = "en"
        
    language = language.lower().strip()
    
    if language not in ["en", "hi", "kn"]:
        language = "en"
        
    signal_dict = TRANSLATIONS.get(signal)
    if not signal_dict:
        # Fallback if signal doesn't have translations
        return f"Detected signal: {signal}"
        
    return signal_dict.get(language, signal_dict.get("en"))
